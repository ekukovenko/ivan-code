def add(a, b):
    """Сложение двух чисел"""
    return a + b

def subtract(a, b):
    """Вычитание: a - b"""
    return a - b  # Исправлено: должно быть a - b

def multiply(a, b):
    """Умножение двух чисел"""
    return a * b

def divide(a, b):
    """Деление: a / b"""
    if b == 0:
        raise ValueError("Ошибка: Деление на ноль!")
    return a / b  # Исправлено: добавлена проверка деления на ноль

# Тестирование (запустите: python calculator.py)
if __name__ == "__main__":
    print("Тестирование калькулятора:")
    print(f"add(2, 3) = {add(2, 3)}")           # Ожидается: 5
    print(f"subtract(5, 3) = {subtract(5, 3)}") # Ожидается: 2
    print(f"multiply(4, 3) = {multiply(4, 3)}") # Ожидается: 12
    print(f"divide(10, 2) = {divide(10, 2)}")   # Ожидается: 5.0
